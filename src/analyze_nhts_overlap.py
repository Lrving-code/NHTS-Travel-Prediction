"""Analyze cross-year variable overlap for prepared NHTS tables."""

from __future__ import annotations

import argparse
import csv
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path


TABLE_DOMAIN_MAP = {
    "HHPUB": "household",
    "HHV2PUB": "household",
    "HHPUB": "household",
    "PERPUB": "person",
    "PERV2PUB": "person",
    "VEHPUB": "vehicle",
    "VEHV2PUB": "vehicle",
    "DAYPUB": "trip",
    "DAYV2PUB": "trip",
    "TRIPPUB": "trip",
    "TRIPV2PUB": "trip",
    "LDTPUB": "long_distance",
    "LDTV2PUB": "long_distance",
}


@dataclass(frozen=True)
class ColumnRecord:
    year: str
    domain: str
    table_name: str
    column_name: str


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--column-inventory",
        type=Path,
        default=Path("outputs/inventory/column_inventory.csv"),
        help="Column inventory generated by inventory_nhts_data.py.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("outputs/inventory"),
        help="Directory where overlap reports will be written.",
    )
    return parser.parse_args()


def normalize_table_name(table_name: str) -> str:
    return table_name.strip().upper()


def normalize_column_name(column_name: str) -> str:
    return column_name.strip().upper()


def infer_domain(table_name: str) -> str:
    normalized = normalize_table_name(table_name)
    return TABLE_DOMAIN_MAP.get(normalized, "unknown")


def load_column_records(path: Path) -> list[ColumnRecord]:
    records: list[ColumnRecord] = []
    with path.open("r", encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle)
        for row in reader:
            table_name = row["table_name"]
            domain = infer_domain(table_name)
            if domain == "unknown":
                continue
            records.append(
                ColumnRecord(
                    year=row["year"],
                    domain=domain,
                    table_name=table_name,
                    column_name=normalize_column_name(row["column_name"]),
                )
            )
    return records


def build_domain_year_columns(
    records: list[ColumnRecord],
) -> dict[str, dict[str, set[str]]]:
    domain_year_columns: dict[str, dict[str, set[str]]] = defaultdict(lambda: defaultdict(set))
    for record in records:
        domain_year_columns[record.domain][record.year].add(record.column_name)
    return domain_year_columns


def write_overlap_csv(
    domain_year_columns: dict[str, dict[str, set[str]]],
    output_dir: Path,
) -> Path:
    output_path = output_dir / "variable_overlap.csv"
    with output_path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["domain", "column_name", "year_count", "years"])
        for domain in sorted(domain_year_columns):
            year_columns = domain_year_columns[domain]
            column_years: dict[str, set[str]] = defaultdict(set)
            for year, columns in year_columns.items():
                for column in columns:
                    column_years[column].add(year)
            for column, years in sorted(column_years.items()):
                writer.writerow([domain, column, len(years), ";".join(sorted(years))])
    return output_path


def format_columns(columns: set[str], limit: int = 40) -> str:
    if not columns:
        return "_None_"
    sorted_columns = sorted(columns)
    shown = sorted_columns[:limit]
    suffix = "" if len(sorted_columns) <= limit else f", ... (+{len(sorted_columns) - limit})"
    return "`" + "`, `".join(shown) + "`" + suffix


def write_overlap_markdown(
    domain_year_columns: dict[str, dict[str, set[str]]],
    output_dir: Path,
) -> Path:
    output_path = output_dir / "variable_overlap_summary.md"
    lines = ["# NHTS Variable Overlap Summary", ""]

    for domain in sorted(domain_year_columns):
        year_columns = domain_year_columns[domain]
        all_years = sorted(year_columns)
        common_columns = set.intersection(*(year_columns[year] for year in all_years))
        union_columns = set.union(*(year_columns[year] for year in all_years))

        lines.extend([f"## {domain}", ""])
        lines.append(f"- Years available: {', '.join(all_years)}")
        lines.append(f"- Union columns: {len(union_columns)}")
        lines.append(f"- Common columns across available years: {len(common_columns)}")
        lines.append("")
        lines.append("| Year | Columns |")
        lines.append("|---|---:|")
        for year in all_years:
            lines.append(f"| {year} | {len(year_columns[year])} |")
        lines.append("")
        lines.append("Common columns:")
        lines.append("")
        lines.append(format_columns(common_columns))
        lines.append("")

    output_path.write_text("\n".join(lines), encoding="utf-8")
    return output_path


def main() -> None:
    args = parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    records = load_column_records(args.column_inventory)
    domain_year_columns = build_domain_year_columns(records)
    overlap_csv = write_overlap_csv(domain_year_columns, args.output_dir)
    overlap_md = write_overlap_markdown(domain_year_columns, args.output_dir)
    print(f"Wrote overlap CSV: {overlap_csv}")
    print(f"Wrote overlap summary: {overlap_md}")


if __name__ == "__main__":
    main()
